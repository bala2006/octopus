// Reading ledger lines: one cell at a time, as text or as a number.

export function readCell0(line) {
  const cells = String(line).split(";");
  const raw = (cells[0] ?? "").trim();
  const asNumber = Number(raw);
  return raw !== "" && Number.isFinite(asNumber) ? asNumber : raw;
}

